'use strict';
/*
 * The Node side of cue_list.py codegen --verify, shared by film_capture.mjs (--cues-gen) and render_block.cjs (the
 * render preload). It rebuilds the constants cue_list.py would write for a cue list (_cues_constants_data) and their
 * CUES_SHA256, and compares them with a times.gen.js/.ts module the way verify_cue_constants does.
 *
 * The two Node checks had each compared only the TIMES and FRAMES of the cues still in the list: a removed cue, a
 * CUES_SHA256 of 64 zeros, a moved section and a shortened silence all passed, and a cue on a half frame was put on
 * the frame Python did not generate. Every rule below is Python's: its rounding (round(x, 6), and a half frame
 * rounding up), its frame-rate parsing (parse_rate, NTSC decimals included) and the bytes of its
 * json.dumps(sort_keys=True), so the hash is the same hash. The self-test runs one table of cases through all three.
 *
 * Known limits, shared with nothing real: JSON.parse cannot tell 5 from 5.0, so a cue list that writes a whole frame
 * number or an arbitrary scale/section value as a decimal with a zero fraction reads as an integer here.
 */
const fs = require('fs');
const path = require('path');
const {createHash} = require('crypto');

const HEADER = '// Generated by cue_list.py codegen';
const GEN_LINE = /^export\s+const\s+[A-Za-z_][A-Za-z0-9_]*\s*=\s*.+?(?:\s+as\s+const)?;$/;
const EXPORT_LINE = /^export\s+const\s+([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.+?)(?:\s+as\s+const)?;\s*$/;
// str.splitlines() boundaries
const LINES = /\r\n|[\n\r\v\f\x1c\x1d\x1e\x85\u2028\u2029]/;
const TIMING_KEYS = ['id', 't', 'frame', 'scale', 'section', 't_end'];
// keyed by cue, section or export names, so without a prototype: in a plain object "__proto__" sets or reads the prototype
const bare = () => Object.create(null);

/** A value Python holds as a float (its repr differs from an integer's: 2.0, not 2). */
class F {
  constructor(x) { this.x = x; }
}
const plain = (v) => (v instanceof F ? v.x : Array.isArray(v) ? v.map(plain)
  : v && typeof v === 'object' ? Object.fromEntries(Object.entries(v).map(([k, x]) => [k, plain(x)])) : v);

/** Python's repr(float). */
function floatRepr(x) {
  if (Number.isNaN(x)) return 'NaN';
  if (x === Infinity) return 'Infinity';
  if (x === -Infinity) return '-Infinity';
  if (x === 0) return Object.is(x, -0) ? '-0.0' : '0.0';
  const [mant, expText] = Math.abs(x).toExponential().split('e');   // the shortest digits that round-trip
  const exp = Number(expText);
  const digits = mant.replace('.', '');
  const sign = x < 0 ? '-' : '';
  if (exp >= -4 && exp < 16) {
    if (exp < 0) return sign + '0.' + '0'.repeat(-exp - 1) + digits;
    if (digits.length <= exp + 1) return sign + digits + '0'.repeat(exp + 1 - digits.length) + '.0';
    return sign + digits.slice(0, exp + 1) + '.' + digits.slice(exp + 1);
  }
  return sign + (digits.length > 1 ? digits[0] + '.' + digits.slice(1) : digits) + 'e' + (exp < 0 ? '-' : '+') +
    String(Math.abs(exp)).padStart(2, '0');
}

/** Python's json.dumps string (ensure_ascii). */
function strJson(s) {
  return JSON.stringify(s).replace(/[\u007f-\uffff]/g, (c) => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'));
}

const byCodePoint = (a, b) => {
  const x = Array.from(a, (c) => c.codePointAt(0)); const y = Array.from(b, (c) => c.codePointAt(0));
  for (let i = 0; i < Math.min(x.length, y.length); i++) if (x[i] !== y[i]) return x[i] - y[i];
  return x.length - y.length;
};

/** Python's json.dumps(value, sort_keys=True) with its default separators. */
function dumps(v) {
  if (v instanceof F) return floatRepr(v.x);
  if (v === null || v === undefined) return 'null';
  if (v === true) return 'true';
  if (v === false) return 'false';
  if (typeof v === 'number') return Number.isInteger(v) ? String(v) : floatRepr(v);
  if (typeof v === 'string') return strJson(v);
  if (Array.isArray(v)) return '[' + v.map(dumps).join(', ') + ']';
  return '{' + Object.keys(v).sort(byCodePoint).map((k) => strJson(k) + ': ' + dumps(v[k])).join(', ') + '}';
}

/** Python's _round6(x) for a float: correctly rounded, an exact tie (x = odd/128) going to the even digit, -0 -> 0. */
function round6(x) {
  if (!Number.isFinite(x) || Math.abs(x) >= 1e15) return x === 0 ? 0 : x;
  const m = x * 128;
  if (Number.isInteger(m) && Math.abs(m) % 2 === 1) {
    const low = (BigInt(Math.trunc(Math.abs(m))) * 1000000n) / 128n;
    const n = low % 2n === 0n ? low : low + 1n;
    const dec = String(n / 1000000n) + '.' + String(n % 1000000n).padStart(6, '0');
    const res = Number((x < 0 ? '-' : '') + dec);
    return res === 0 ? 0 : res;
  }
  const r = Number(x.toFixed(6));
  return r === 0 ? 0 : r;
}

// cue_list.MIN_FPS, MAX_FPS, MAX_SIDE, MAX_CUE_SECONDS and MAX_FRAME: within them both compute the same numbers,
// past them both refuse with the same message
const MIN_FPS = 1;
const MAX_FPS = 1000;
const MAX_SIDE = 32768;
const MAX_CUE_SECONDS = 1e9;
const MAX_FRAME = Number.MAX_SAFE_INTEGER;
// cue_list.ID_RULE and _id_text: a cue's id is text, or a number with a whole value within MAX_FRAME either way
const ID_RULE = `an id must be text, or a whole number from -${MAX_FRAME} to ${MAX_FRAME}; write any other id as text, ` +
  'in double quotes';
function idText(v) {
  if (typeof v === 'string') return v;
  return typeof v === 'number' && Number.isSafeInteger(v) ? String(v) : null;   // String(-0) is "0", as in Python
}

/** cue_list._name: a name CUES_SHA256 covers as it is written (a cue's scale and section, a section's clock) is
 * text or nothing; a number there is written 1.0 by Python and 1 here. */
function nameText(v, label, cuesName) {
  if (v === null || v === undefined) return null;
  if (typeof v === 'string') return v;
  throw Error(`${cuesName}: ${label} must be text, in double quotes`);
}

/** cue_list._cue_time: SECONDS, refused past MAX_CUE_SECONDS either way. */
function cueTime(seconds, cuesName) {
  if (Math.abs(seconds) > MAX_CUE_SECONDS) {
    throw Error(`${cuesName}: a cue time is beyond ${MAX_CUE_SECONDS} s (about 31.7 years), the longest ` +
      'cue_list.py and the Node checks agree on');
  }
  return seconds;
}

/** The frame nearest t*fps, a half frame rounding up (cue_list._frame_at, the kit engine's Math.round). */
function frameAt(x) {
  if (!Number.isFinite(x) || Math.abs(x) > MAX_FRAME) throw Error('cue time overflows frame count');
  return Math.round(x);
}

/** Python's truthiness for a JSON value. */
const truthy = (v) => !(v === null || v === undefined || v === false || v === 0 || v === '' ||
  (Array.isArray(v) && !v.length) || (typeof v === 'object' && !Array.isArray(v) && !Object.keys(v).length));

const ASCII_TRIM = /^[\x20\t\n\r\f\v]+|[\x20\t\n\r\f\v]+$/g;
const ASCII_DECIMAL = /^[+-]?(?:[0-9]+\.?[0-9]*(?:[eE][+-]?[0-9]+)?|\.[0-9]+(?:[eE][+-]?[0-9]+)?)$/;

/** cue_list._finite_num: finite number or ASCII decimal string (no booleans, NaN, Infinity or underscores). */
function finiteNum(v, label, cuesName) {
  const bad = () => Error(`${cuesName}: ${label} must be a finite number`);
  if (typeof v === 'boolean' || v === null || v === undefined) throw bad();
  let num;
  if (typeof v === 'number') {
    num = v;
  } else if (typeof v === 'string') {
    const text = v.replace(ASCII_TRIM, '');
    if (!ASCII_DECIMAL.test(text)) throw bad();
    num = Number(text);
  } else {
    throw bad();
  }
  if (!Number.isFinite(num)) throw bad();
  return num;
}

/** Python's max(values, default=0.0). */
const maxOr0 = (values) => (values.length ? Math.max(...values) : 0.0);

function gcd(a, b) { while (b) { [a, b] = [b, a % b]; } return a < 0n ? -a : a; }

/** float(Fraction(x).limit_denominator(1001)) for a positive finite double, exactly as CPython computes it. */
function limitDenominator(x, maxDen = 1001n) {
  const view = new DataView(new ArrayBuffer(8));
  view.setFloat64(0, x);
  const hi = view.getUint32(0); const lo = view.getUint32(4);
  const biased = (hi >>> 20) & 0x7ff;
  let mant = (BigInt(hi & 0xfffff) << 32n) | BigInt(lo);
  let e;
  if (biased === 0) e = -1074; else { mant |= 1n << 52n; e = biased - 1075; }
  let num = mant; let den = 1n;
  if (e > 0) num <<= BigInt(e); else den <<= BigInt(-e);
  const g = gcd(num, den); num /= g; den /= g;
  if (den <= maxDen) return Number(num) / Number(den);
  let p0 = 0n; let q0 = 1n; let p1 = 1n; let q1 = 0n; let n = num; let d = den;
  for (;;) {
    const a = n / d;
    const q2 = q0 + a * q1;
    if (q2 > maxDen) break;
    [p0, q0, p1, q1] = [p1, q1, p0 + a * p1, q2];
    [n, d] = [d, n - a * d];
  }
  const k = (maxDen - q0) / q1;
  // the nearer of p1/q1 and (p0+k*p1)/(q0+k*q1), p1/q1 on a tie (CPython's rule)
  const b1n = p0 + k * p1; const b1d = q0 + k * q1;
  const dist = (pn, pd) => { const t = pn * den - num * pd; return [t < 0n ? -t : t, pd * den]; };
  const [d2n, d2d] = dist(p1, q1); const [d1n, d1d] = dist(b1n, b1d);
  return d2n * d1d <= d1n * d2d ? Number(p1) / Number(q1) : Number(b1n) / Number(b1d);
}

/** float(cue_list._read_rate(value)): zero for a rate that limits to 0 at denominator 1001. */
function parseRate(value) {
  const bad = () => Error('fps must be a positive number or a rational string such as "24000/1001"');
  if (value === null || value === undefined || typeof value === 'boolean') throw bad();
  let number;
  if (typeof value === 'string') {
    const text = value.replace(ASCII_TRIM, '');
    const m = /^([0-9]+)(?:\/([0-9]+))?$/.exec(text);
    if (m) {
      // cue_list._read_rate: a part past MAX_FRAME is read exactly there and rounded here, so it is refused in both
      const limit = String(MAX_FRAME);
      if ([m[1], m[2]].some((p) => p !== undefined && (p.replace(/^0+/, '').length > limit.length || Number(p) > MAX_FRAME))) {
        throw Error(`fps ${text} has a numerator or denominator beyond ${MAX_FRAME}, the largest whole number ` +
          'cue_list.py and the Node checks both read exactly: write it with smaller numbers');
      }
      const den = m[2] === undefined ? 1 : Number(m[2]);
      if (den === 0) throw bad();
      return Number(m[1]) / den;
    }
    if (!ASCII_DECIMAL.test(text)) throw bad();
    number = Number(text);
  } else if (typeof value === 'number') {
    number = value;
  } else {
    throw bad();
  }
  if (!Number.isFinite(number) || number <= 0) throw bad();
  const ntsc = number * 1001 / 1000;
  if (Math.abs(number - Math.round(number)) > 1e-9 && Math.abs(ntsc - Math.round(ntsc)) < 0.01) {
    return (Math.round(ntsc) * 1000) / 1001;
  }
  return limitDenominator(number);
}

function sanitizeIdent(id) {
  const cleaned = String(id).replace(/[^A-Za-z0-9]+/g, '_').replace(/^_+|_+$/g, '').toUpperCase();
  return `CUE_${cleaned || 'ITEM'}`;
}

/** cue_list.parse_cues_gen_env: a JSON list of module paths, or a single bare path. */
function parseCuesGenEnv(raw) {
  const text = String(raw || '');
  if (!text.trim()) return [];
  if (text.trimStart().startsWith('[')) {
    try {
      const parsed = JSON.parse(text);
      if (Array.isArray(parsed) && parsed.every((x) => typeof x === 'string' && x)) return parsed;
    } catch (_) { /* single bare path starting with '[' */ }
  }
  return [text];
}

/** cue_list._cues_constants_data: {CUES_SHA256, CLOCK, SECTIONS, TIMES, FRAMES, CUES, named}, plain numbers. */
function expectedConstants(cuesFile) {
  const cuesName = path.basename(cuesFile);
  const doc = JSON.parse(fs.readFileSync(cuesFile).toString('utf8'));
  if (!doc || typeof doc !== 'object' || Array.isArray(doc)) throw Error(`${cuesFile} must contain a JSON object`);
  const fps = doc.fps !== null && doc.fps !== undefined ? parseRate(doc.fps) : 60.0;
  if (!(fps >= MIN_FPS && fps <= MAX_FPS)) {
    throw Error(`${cuesName}: fps must be from ${MIN_FPS} to ${MAX_FPS} frames a second, the range cue_list.py ` +
      'and the Node checks are held to agree on');
  }
  const exp = doc.export && typeof doc.export === 'object' && !Array.isArray(doc.export) ? doc.export : {};
  // only text is a size, here and in cue_list.py: String() of a list holding "800x600" is that text, and was read as one
  const size = (truthy(exp.size) ? exp.size : null) ?? (truthy(doc.size) ? doc.size : null) ?? '1920x1080';
  const sizeText = typeof size === 'string' ? size : '';
  const m = /^([0-9]+)x([0-9]+)$/.exec(sizeText);
  const limit = String(MAX_SIDE);
  if (m && ![m[1], m[2]].every((p) => p.replace(/^0+/, '').length <= limit.length && Number(p) >= 1 && Number(p) <= MAX_SIDE)) {
    throw Error(`${cuesName}: size ${sizeText} must have a width and height from 1 to ${MAX_SIDE}`);
  }
  const [width, height] = m ? [Number(m[1]), Number(m[2])] : [1920, 1080];
  let dur = truthy(exp.duration) ? exp.duration : doc.duration;
  const dicts = (list) => (Array.isArray(list) ? list.filter((x) => x && typeof x === 'object' && !Array.isArray(x)) : []);
  if ((dur === null || dur === undefined) && Array.isArray(doc.sections) && doc.sections.length) {
    dur = maxOr0(dicts(doc.sections).map((s) => finiteNum(truthy(s.b) ? s.b : 0, 'section b', cuesName)));
  }
  if ((dur === null || dur === undefined) && Array.isArray(doc.events) && doc.events.length) {
    dur = maxOr0(dicts(doc.events).map((e) => finiteNum(truthy(e.t_end) ? e.t_end : truthy(e.t) ? e.t : 0, 'event time', cuesName)));
  }
  const durS = cueTime(round6(finiteNum(truthy(dur) ? dur : 0.0, 'duration', cuesName)), cuesName);
  const clock = {fps: Number.isInteger(fps) ? fps : new F(round6(fps)), width, height, duration_s: new F(durS),
    duration_frames: durS ? frameAt(durS * fps) : 0};
  // a section's id is text, as the cue list reader has always held it to; a cue's is text or a whole number
  (Array.isArray(doc.sections) ? doc.sections : []).forEach((x, i) => {
    if (x && typeof x === 'object' && !Array.isArray(x) && 'id' in x && typeof x.id !== 'string') {
      throw Error(`${cuesName}: section ${i}: a section's id must be text, in double quotes`);
    }
  });
  (Array.isArray(doc.events) ? doc.events : []).forEach((x, i) => {
    if (x && typeof x === 'object' && !Array.isArray(x) && 'id' in x && idText(x.id) === null) {
      throw Error(`${cuesName}: event ${i}: ${ID_RULE}`);
    }
  });
  // cue_list.py refuses the id "__proto__": in the generated modules' object literals it sets the prototype
  const reserved = [...new Set([...dicts(doc.sections), ...dicts(doc.events)].filter((x) => 'id' in x)
    .map((x) => idText(x.id)).filter((id) => id === '__proto__'))];
  if (reserved.length) {
    throw Error(`${cuesName}: the id "__proto__" cannot be a key in the generated timing modules (an object ` +
      'literal takes it as the prototype and the film loses the cue); rename it');
  }
  const sections = bare();
  for (const sec of dicts(doc.sections)) {
    if (!('id' in sec)) continue;
    const sid = idText(sec.id);
    const a = cueTime(round6(finiteNum(truthy(sec.a) ? sec.a : 0.0, `section ${JSON.stringify(sid)} a`, cuesName)), cuesName);
    const b = cueTime(round6(finiteNum(truthy(sec.b) ? sec.b : 0.0, `section ${JSON.stringify(sid)} b`, cuesName)), cuesName);
    sections[sid] = {a: new F(a), b: new F(b), a_frame: frameAt(a * fps), b_frame: frameAt(b * fps),
      clock: nameText(sec.clock, `section ${JSON.stringify(sid)} clock`, cuesName)};
  }
  const times = bare(); const frames = bare(); const cues = []; const named = bare(); const used = new Set();
  for (const ev of dicts(doc.events)) {
    if (!('id' in ev)) continue;
    const id = idText(ev.id);
    if (ev.frame !== null && ev.frame !== undefined) frameAt(finiteNum(ev.frame, `event ${JSON.stringify(id)} frame`, cuesName));
    const t = cueTime(round6(ev.t !== null && ev.t !== undefined ? finiteNum(ev.t, `event ${JSON.stringify(id)} t`, cuesName)
      : finiteNum(truthy(ev.frame) ? ev.frame : 0, `event ${JSON.stringify(id)} frame`, cuesName) / fps), cuesName);
    const frame = typeof ev.frame === 'number' && Number.isInteger(ev.frame) ? ev.frame : frameAt(t * fps);
    const entry = {id, t: new F(t), frame,
      scale: 'scale' in ev ? nameText(ev.scale, `event ${JSON.stringify(id)} scale`, cuesName) : 'contact'};
    if (truthy(ev.role)) entry.role = ev.role;
    // held to text before it is passed over as empty: 0, false and [] are refused, as for scale and clock
    const section = nameText(ev.section, `event ${JSON.stringify(id)} section`, cuesName);
    if (section) entry.section = section;
    if (truthy(ev.picture)) entry.note = ev.picture;
    if (ev.t_end !== null && ev.t_end !== undefined) {
      entry.t_end = new F(cueTime(round6(finiteNum(ev.t_end, `event ${JSON.stringify(id)} t_end`, cuesName)), cuesName));
    }
    times[id] = new F(t);
    frames[id] = frame;
    cues.push(entry);
    let ident = sanitizeIdent(id);
    if (used.has(ident)) {
      let k = 2;
      while (used.has(`${ident}_${k}`)) k++;
      ident = `${ident}_${k}`;
    }
    used.add(ident);
    named[ident] = entry;
  }
  const timingOf = (entry) => Object.fromEntries(TIMING_KEYS.filter((k) => k in entry).map((k) => [k, entry[k]]));
  const sha = createHash('sha256').update(dumps({CLOCK: clock, SECTIONS: sections, TIMES: times, FRAMES: frames,
    CUES: cues.map(timingOf)}), 'utf8').digest('hex');
  return {CUES_SHA256: sha, CLOCK: plain(clock), SECTIONS: plain(sections), TIMES: plain(times), FRAMES: plain(frames),
    CUES: plain(cues), named: plain(named)};
}

/** Python's == for parsed JSON values. */
function same(a, b) {
  if (a === b) return true;
  if (typeof a === 'number' && typeof b === 'number') return a === b;
  if (Array.isArray(a) || Array.isArray(b)) {
    return Array.isArray(a) && Array.isArray(b) && a.length === b.length && a.every((x, i) => same(x, b[i]));
  }
  if (a && b && typeof a === 'object' && typeof b === 'object') {
    const ka = Object.keys(a); const kb = Object.keys(b);
    return ka.length === kb.length && ka.every((k) => Object.prototype.hasOwnProperty.call(b, k) && same(a[k], b[k]));
  }
  return false;
}

const timing = (entry) => Object.fromEntries(TIMING_KEYS.filter((k) => entry && typeof entry === 'object' && k in entry)
  .map((k) => [k, entry[k]]));

/** cue_list.verify_cue_constants: [] when GEN_FILE holds the constants of CUES_FILE, else what differs. */
function verifyGenerated(cuesFile, genFile) {
  const name = path.basename(genFile);
  if (!fs.existsSync(genFile)) return [`${genFile} does not exist`];
  const expected = expectedConstants(cuesFile);
  const text = fs.readFileSync(genFile, 'utf8');
  const lines = text.split(LINES);
  if (lines.length && lines[lines.length - 1] === '') lines.pop();
  const actual = bare();
  try {
    for (const line of lines) {
      const m = EXPORT_LINE.exec(line);
      if (m) actual[m[1]] = JSON.parse(m[2]);
    }
  } catch (err) {
    return [`${genFile} could not be parsed: ${err.message}`];
  }
  const problems = [];
  const stray = lines.slice(1).find((ln) => ln.trim() && !GEN_LINE.test(ln.trim()));
  if (!lines.length || !lines[0].startsWith(HEADER) || stray !== undefined) {
    problems.push(`${name}: holds lines cue_list.py did not write` + (stray !== undefined ? ` (${JSON.stringify(stray.slice(0, 60))})` : ''));
  }
  if (actual.CUES_SHA256 !== expected.CUES_SHA256) {
    problems.push(`${name}: CUES_SHA256 ${JSON.stringify(actual.CUES_SHA256)} != the cue list's timing ${JSON.stringify(expected.CUES_SHA256)}`);
  }
  for (const key of ['CLOCK', 'SECTIONS', 'TIMES', 'FRAMES']) {
    if (!same(actual[key], expected[key])) problems.push(`${name}: ${key} differs from cues.json`);
  }
  if (!same((Array.isArray(actual.CUES) ? actual.CUES : []).map(timing), expected.CUES.map(timing))) {
    problems.push(`${name}: CUES differs from cues.json`);
  }
  for (const [ident, entry] of Object.entries(expected.named)) {
    if (!same(timing(actual[ident] || {}), timing(entry))) problems.push(`${name}: constant ${ident} differs from cues.json`);
  }
  return problems;
}

module.exports = {expectedConstants, verifyGenerated, parseCuesGenEnv, dumps, floatRepr, round6, parseRate, F};
